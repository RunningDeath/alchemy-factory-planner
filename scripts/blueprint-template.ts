#!/usr/bin/env bun

/**
 * Writes engine/build/blueprint/template-data.ts: the parts of real player blueprints
 * (engine/build/blueprint/fixtures) that exported blueprints copy every field from that
 * the app doesn't control: the file header, one plain building, one conveyor lift
 * (with its stacked pieces) and the top-level properties after the building list.
 *
 * Usage: bun run scripts/blueprint-template.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { encodeProperties, decodeProperties, findProp, type Property, type Value } from '../engine/build/blueprint/properties';
import { readBlueprintTail } from '../engine/build/blueprint/file';

const DIR = './engine/build/blueprint/fixtures/';
const OUT = './engine/build/blueprint/template-data.ts';

const header = readBlueprintTail(new Uint8Array(readFileSync(DIR + 'leinoel.tail.bin'))).header;
const body = decodeProperties(new Uint8Array(gunzipSync(readFileSync(DIR + 'monteur.body.bin.gz'))));

const buildings = findProp(body, 'Buildings')!.value as Property[][];
const nameOf = (b: Property[]) => (findProp(findProp(b, 'building')!.value as Property[], 'BuildingName')!.value as string);
const hasExtension = (b: Property[]) => (findProp(b, 'Extension')!.value as Value[]).length > 0;

const plain = buildings.find((b) => nameOf(b) === 'FrameSingle' && !hasExtension(b));
const lift = buildings.find((b) => nameOf(b) === 'ConveyerLift_Upwards' && hasExtension(b));
if (!plain || !lift) throw new Error('template buildings not found');

const template = body.map((p) => (p.name === 'Buildings' ? { ...p, value: [plain, lift] } : p));
const b64 = (bytes: Uint8Array) => Buffer.from(bytes).toString('base64');

writeFileSync(
  OUT,
  `// Generated by scripts/blueprint-template.ts from the player blueprints in ./fixtures. Do not edit.\n\n` +
    `/** Blueprint file header properties (tagged, ending in None) */\n` +
    `export const HEADER_B64 = "${b64(encodeProperties(header))}";\n\n` +
    `/** Blueprint body: Buildings = [a FrameSingle, a ConveyerLift_Upwards with its pieces], then the other top-level properties */\n` +
    `export const BODY_B64 = "${b64(encodeProperties(template))}";\n`,
);
console.log(`Wrote ${OUT}`);
